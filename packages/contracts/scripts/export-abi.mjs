// Writes packages/config/src/abi/<Contract>.ts from the forge build artifacts.
// Run after `forge build`: node scripts/export-abi.mjs
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = [
  { file: "BallIsFlat.sol", name: "BallIsFlat", exportName: "ballIsFlatAbi" },
  { file: "BallIsFlatHunt.sol", name: "BallIsFlatHunt", exportName: "ballIsFlatHuntAbi" },
];

for (const { file, name, exportName } of contracts) {
  const artifact = resolve(here, `../out/${file}/${name}.json`);
  const target = resolve(here, `../../config/src/abi/${name}.ts`);
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  if (!Array.isArray(abi) || abi.length === 0) throw new Error(`no abi in ${artifact}`);
  const body =
    `// Generated by packages/contracts/scripts/export-abi.mjs from out/${file}/${name}.json.\n` +
    "// Do not edit by hand: change the contract, run `forge build`, then `node scripts/export-abi.mjs`.\n" +
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, body);
  // Same style as the rest of the repo, so `npm run lint` passes on the generated file.
  execFileSync("npx", ["biome", "format", "--write", target], { stdio: "ignore" });
  console.log(`wrote ${abi.length} abi entries to ${target}`);
}
