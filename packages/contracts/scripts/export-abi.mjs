// Writes packages/config/src/abi/BallIsFlat.ts from the forge build artifact.
// Run after `forge build`: node scripts/export-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../out/BallIsFlat.sol/BallIsFlat.json");
const target = resolve(here, "../../config/src/abi/BallIsFlat.ts");

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
if (!Array.isArray(abi) || abi.length === 0) throw new Error(`no abi in ${artifact}`);

const body =
  "// Generated by packages/contracts/scripts/export-abi.mjs from out/BallIsFlat.sol/BallIsFlat.json.\n" +
  "// Do not edit by hand: change the contract, run `forge build`, then `node scripts/export-abi.mjs`.\n" +
  `export const ballIsFlatAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, body);
console.log(`wrote ${abi.length} abi entries to ${target}`);
